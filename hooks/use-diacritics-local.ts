export const useDiacritics = () => {
  // Ajouter les voyelles à un mot
  const addDiacriticsToWord = useCallback((word: string): string => {
    if (ARABIC_DICTIONARY[word]) {
      return ARABIC_DICTIONARY[word];
    }
    return word;
  }, []);

  // Ajouter les voyelles à un texte complet
  const addDiacriticsToText = useCallback((text: string): string => {
    const words = text.split(' ');
    const diacriticWords = words.map((word) => {
      const diacriticWord = addDiacriticsToWord(word);
      return diacriticWord;
    });
    return diacriticWords.join(' ');
  }, [addDiacriticsToWord]);

  // Obtenir le dictionnaire
  const getDictionary = useCallback(() => ARABIC_DICTIONARY, []);

  return {
    addDiacriticsToWord,
    addDiacriticsToText,
    getDictionary,
  };
};
